"""Lead routing table: (region × process) -> matching shops from content/shops.json.

Built for a later per-lead fee: a quote request for "plasma" in "mauricie" can be sent to the
shops listed under that cell. Nothing is sent automatically today; api/quote-request.js only
forwards requests to info@coupefab.ca. Regenerate: python3 -m revenue.routing
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "revenue" / "lead-routing.json"

# form value -> (FR label, EN label, guides in content/shops.json "by_guide")
PROCESSES = {
    "plasma": ("Découpe plasma", "Plasma cutting", ["plasma-cutting", "plasma-bevel", "oxyfuel"]),
    "laser": ("Découpe laser", "Laser cutting", ["fiber-laser"]),
    "waterjet": ("Jet d’eau", "Waterjet", ["waterjet"]),
    "bending": ("Pliage", "Bending / press brake", ["press-brake"]),
    "machining": ("Usinage CNC (fraisage, tournage)", "CNC machining (milling, turning)", ["cnc-mill", "cnc-lathe", "five-axis", "swiss-turn-mill", "edm"]),
    "router": ("Routeur CNC", "CNC routing", ["cnc-router"]),
    "welding": ("Soudage et finition", "Welding and finishing", ["weld-prep", "deburring"]),
    "other": ("Autre / je ne sais pas", "Other / not sure", []),
}
REGIONS = {
    "montreal": ("Montréal et Laval", "Montreal and Laval"),
    "monteregie": ("Montérégie", "Montérégie"),
    "laurentides-lanaudiere": ("Laurentides et Lanaudière", "Laurentides and Lanaudière"),
    "mauricie-centre": ("Mauricie et Centre-du-Québec", "Mauricie and Centre-du-Québec"),
    "quebec-chaudiere": ("Québec et Chaudière-Appalaches", "Quebec City and Chaudière-Appalaches"),
    "saguenay": ("Saguenay–Lac-Saint-Jean", "Saguenay–Lac-Saint-Jean"),
    "autre-qc": ("Ailleurs au Québec", "Elsewhere in Quebec"),
    "hors-qc": ("Hors Québec", "Outside Quebec"),
}
CITY_REGION = {
    "Montréal": "montreal", "Saint-Laurent (Montréal)": "montreal", "Saint-Léonard (Montréal)": "montreal", "Laval": "montreal",
    "Boucherville": "monteregie", "Châteauguay": "monteregie", "Saint-Jean-sur-Richelieu": "monteregie", "Saint-Pie": "monteregie",
    "Saint-Télesphore": "monteregie",
    "Saint-Eustache": "laurentides-lanaudiere", "Terrebonne": "laurentides-lanaudiere", "Lanoraie": "laurentides-lanaudiere",
    "Berthierville": "laurentides-lanaudiere",
    "Louiseville": "mauricie-centre", "Drummondville": "mauricie-centre", "Nicolet": "mauricie-centre",
    "Grand-Saint-Esprit": "mauricie-centre", "Sainte-Claire": "quebec-chaudiere", "Saint-Prosper": "quebec-chaudiere",
    "Québec": "quebec-chaudiere", "Saint-Marc-des-Carrières": "quebec-chaudiere",
    "Jonquière (Saguenay)": "saguenay",
}


def build_table() -> dict:
    d = json.loads((ROOT / "content" / "shops.json").read_text(encoding="utf-8"))
    shops, by_guide = d["shops"], d["by_guide"]
    table = {r: {p: [] for p in PROCESSES} for r in REGIONS}
    unmapped = []
    for p, (_, _, guides) in PROCESSES.items():
        ids = sorted({sid for g in guides for sid in by_guide.get(g, [])})
        for sid in ids:
            reg = CITY_REGION.get(shops.get(sid, {}).get("city", ""))
            if not reg:
                unmapped.append(sid); reg = "autre-qc"
            table[reg][p].append(sid)
    return {"_doc": "Generated by python3 -m revenue.routing from content/shops.json. Region x process -> shop ids. "
                    "Used later for per-lead routing; nothing is sent to shops today.",
            "processes": {k: [v[0], v[1]] for k, v in PROCESSES.items()},
            "regions": {k: list(v) for k, v in REGIONS.items()},
            "table": table, "unmapped_cities": sorted(set(unmapped))}


def write() -> Path:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    t = build_table()
    OUT.write_text(json.dumps(t, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    # same table for api/quote-request.js (files starting with _ are bundled, not exposed as functions)
    (ROOT / "api" / "_lead-routing.js").write_text(
        "// Generated by python3 -m revenue.routing — do not edit. Region x process -> shop ids (content/shops.json).\n"
        "module.exports = " + json.dumps({"table": t["table"]}, ensure_ascii=False) + ";\n", encoding="utf-8")
    return OUT


if __name__ == "__main__":
    print(write())
